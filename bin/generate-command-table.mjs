#!/usr/bin/env node
// Regenerate src/binary/command-table.gen.ts from the CLI manifest (spec
// Unit 2). The compiled binary cannot follow the router's computed dynamic
// imports (bun bundles only statically-analyzable specifiers), so every
// manifest leaf gets a static import thunk here; the binary entry installs
// the table on globalThis and dispatch() consults it first. A unit test
// asserts the committed file matches the manifest — run this script whenever
// a manifest src is added, moved, or removed.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const { MANIFEST } = await import(join(root, 'dist/cli/manifest.js'));

const srcs = [
  ...new Set(Object.values(MANIFEST).flatMap((g) => Object.values(g.subs).map((s) => s.src))),
].sort();

const thunks = srcs
  .map((src) => `  '${src}': () => import('../${src.replace(/\.ts$/, '.js')}'),`)
  .join('\n');

const out = `// GENERATED by bin/generate-command-table.mjs — do not edit by hand.
// Static import thunk per CLI-manifest leaf so \`bun build --compile\` sees
// the whole command graph (the router's computed dynamic imports are opaque
// to the bundler). Consumed only by the binary entry (spec Unit 2); the npm
// channel never imports this module.

/* eslint-disable */
export const COMMAND_IMPORTS: Record<string, () => Promise<unknown>> = {
${thunks}
};
`;

const target = join(root, 'src/binary/command-table.gen.ts');
const prev = (() => {
  try {
    return readFileSync(target, 'utf8');
  } catch {
    return null;
  }
})();
if (prev === out) {
  console.log(`command-table: up to date (${srcs.length} entries)`);
} else {
  writeFileSync(target, out);
  console.log(`command-table: wrote ${srcs.length} entries to src/binary/command-table.gen.ts`);
}
